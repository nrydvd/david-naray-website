const localeKey = "davidnaray-language";
const supportedLocales = ["hu", "en", "de"];
let activeLocale = "hu";

try {
    const savedLocale = localStorage.getItem(localeKey);
    if (supportedLocales.includes(savedLocale)) {
        activeLocale = savedLocale;
    }
} catch (error) {
}

const sourceText = new WeakMap();
const sourceAttributes = new WeakMap();
const translatableAttributes = ["aria-label", "alt", "content", "value"];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
const pageTextNodes = [];

while (textWalker.nextNode()) {
    const node = textWalker.currentNode;
    if (node.nodeValue.trim()) {
        sourceText.set(node, node.nodeValue);
        pageTextNodes.push(node);
    }
}

const pageAttributeElements = Array.from(document.querySelectorAll(
    "[aria-label], img[alt], input[name='subject']"
));
pageAttributeElements.forEach((element) => {
    const values = {};
    translatableAttributes.forEach((attribute) => {
        if (element.hasAttribute(attribute)) {
            values[attribute] = element.getAttribute(attribute);
        }
    });
    sourceAttributes.set(element, values);
});

function translatePage(locale) {
    activeLocale = locale;
    const dictionary = pageTranslations[locale] || {};

    pageTextNodes.forEach((node) => {
        const original = sourceText.get(node);
        const key = original.trim().replace(/\s+/g, " ");
        const leading = original.match(/^\s*/)[0];
        const trailing = original.match(/\s*$/)[0];
        node.nodeValue = `${leading}${dictionary[key] || key}${trailing}`;
    });

    pageAttributeElements.forEach((element) => {
        const originalValues = sourceAttributes.get(element);
        Object.entries(originalValues).forEach(([attribute, original]) => {
            const key = original.trim().replace(/\s+/g, " ");
            element.setAttribute(attribute, dictionary[key] || key);
        });
    });

    document.documentElement.lang = locale;

    document.querySelectorAll("[data-language]").forEach((control) => {
        if (control.dataset.language === locale) {
            control.setAttribute("aria-current", "page");
        } else {
            control.removeAttribute("aria-current");
        }
    });
}

document.querySelectorAll("[data-language]").forEach((control) => {
    control.addEventListener("click", (event) => {
        event.preventDefault();
        const locale = control.dataset.language;
        if (!supportedLocales.includes(locale)) {
            return;
        }
        try {
            localStorage.setItem(localeKey, locale);
        } catch {
        }
        translatePage(locale);
    });
});

translatePage(activeLocale);

